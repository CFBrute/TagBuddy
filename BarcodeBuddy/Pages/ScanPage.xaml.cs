using BarcodeBuddy.Models;
using BarcodeBuddy.Services;
using ZXing.Net.Maui;

namespace BarcodeBuddy.Pages;

public partial class ScanPage : ContentPage
{
    private readonly FavoritesService _favorites;
    private BarcodeResult? _last;

    public ScanPage(FavoritesService favorites)
    {
        InitializeComponent();
        _favorites = favorites;

        Camera.Options = new BarcodeReaderOptions
        {
            Formats = BarcodeFormat.Code128 | BarcodeFormat.Code39 | BarcodeFormat.Code93 |
                      BarcodeFormat.Ean13 | BarcodeFormat.Ean8 | BarcodeFormat.UpcA | BarcodeFormat.UpcE |
                      BarcodeFormat.Itf | BarcodeFormat.Codabar | BarcodeFormat.QrCode |
                      BarcodeFormat.DataMatrix,
            AutoRotate = true,
            Multiple = false,
            TryHarder = true,
        };
    }

    protected override async void OnAppearing()
    {
        base.OnAppearing();

        var status = await Permissions.CheckStatusAsync<Permissions.Camera>();
        if (status != PermissionStatus.Granted)
            status = await Permissions.RequestAsync<Permissions.Camera>();

        var granted = status == PermissionStatus.Granted;
        PermissionLabel.IsVisible = !granted;
        Camera.IsVisible = granted;
        TorchButton.IsVisible = granted;
        Camera.IsDetecting = granted;
    }

    protected override void OnDisappearing()
    {
        base.OnDisappearing();
        Camera.IsDetecting = false;
        Camera.IsTorchOn = false;
    }

    private void OnBarcodesDetected(object? sender, BarcodeDetectionEventArgs e)
    {
        var result = e.Results.FirstOrDefault();
        if (result is null) return;

        MainThread.BeginInvokeOnMainThread(() =>
        {
            Camera.IsDetecting = false;
            _last = result;

            var format = BarcodeTypes.FromZxing(result.Format);
            StatusLabel.Text = format?.Label ?? result.Format.ToString();
            ResultLabel.Text = result.Value;
            ResultButtons.IsVisible = true;
            ScanAgainButton.IsVisible = true;

            try { Vibration.Default.Vibrate(80); } catch { /* not supported on every device */ }
        });
    }

    private void OnScanAgain(object? sender, EventArgs e)
    {
        _last = null;
        StatusLabel.Text = "Point the camera at a barcode";
        ResultLabel.Text = string.Empty;
        ResultButtons.IsVisible = false;
        ScanAgainButton.IsVisible = false;
        Camera.IsDetecting = true;
    }

    private void OnTorch(object? sender, EventArgs e) => Camera.IsTorchOn = !Camera.IsTorchOn;

    private async void OnUseInGenerator(object? sender, EventArgs e)
    {
        if (_last is null) return;
        var format = BarcodeTypes.FromZxing(_last.Format)?.Key ?? "Code128";
        await Shell.Current.GoToAsync("//generate", new Dictionary<string, object>
        {
            ["value"] = _last.Value,
            ["format"] = format,
        });
    }

    private async void OnSave(object? sender, EventArgs e)
    {
        if (_last is null) return;
        var format = BarcodeTypes.FromZxing(_last.Format);
        if (format is null)
        {
            await DisplayAlertAsync("Not supported", $"{_last.Format} can be scanned but not generated by this app.", "OK");
            return;
        }
        if (_favorites.Contains(_last.Value, format.Key))
        {
            await DisplayAlertAsync("Already saved", "This barcode is already in your favorites.", "OK");
            return;
        }

        var name = await DisplayPromptAsync("Add to favorites", "Give it a name (optional):",
            accept: "Save", cancel: "Cancel", placeholder: _last.Value, maxLength: 60);
        if (name is null) return;

        await _favorites.AddAsync(new BarcodeItem { Name = name.Trim(), Value = _last.Value, Format = format.Key });
        await DisplayAlertAsync("Saved to favorites", null, "OK");
    }

    private async void OnCopy(object? sender, EventArgs e)
    {
        if (_last is null) return;
        await Clipboard.Default.SetTextAsync(_last.Value);
        await DisplayAlertAsync("Copied", null, "OK");
    }
}
